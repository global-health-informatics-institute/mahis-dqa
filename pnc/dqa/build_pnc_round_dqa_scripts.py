"""Generates the ROUND-LEVEL DQA scripts for PNC, one unit per row:
  * Vitals encounters of women -> input table/CTE `mahis_vitals`     (../mahis_pnc_vitals.sql)
Fields are the dictionary's ld_mon_exam_* / ld_mon_vitals_* fields (Required = Yes), each required in every round/encounter."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
NUM_RX = r"'^[ ]*-?[0-9]+(\\.[0-9]+)?[ ]*$'"

CONFIGS = [
    dict(tag="vitals", table="mahis_vitals", where="record_type = 'woman'", unit="Vitals encounter", units="encounters", nums=(21, 22, 23, 24), reading=True,
         title="PNC VITALS ENCOUNTERS (women)", id_cols="m.person_id, m.location_id, m.encounter_id, m.visit_date, m.encounter_time",
         rules=[("systolic_blood_pressure", "pnc_ward_mom_systolic_blood_pressu", "Systolic pressure"), ("diastolic_blood_pressure", "pnc_ward_mom_diastolic_blood_press", "Diastolic pressure"),
                ("pulse", "pnc_ward_mom_pulse", "Pulse rate"), ("temperature_c", "pnc_ward_mom_temperature", "Temperature"),
                ("respiratory_rate", "pnc_ward_mom_respiratory_rate", "Respiratory rate"), ("sao2", "pnc_ward_mom_oxygen_saturation", "Oxygen saturation")],
         not_assessable=[("pnc_ward_mom_* (ward monitoring mother encounters)", "Dictionary lists these vitals under 'postnatal ward monitoring - mother'",
                          "in the data the mother's vitals are in the Vitals encounters (assessed here); the 'PNC ward monitoring mother' encounters hold no vitals")]),
]

HEADER = """-- ============================================================================
-- {title}
-- INPUT: a table or CTE named `{table}` (output of {src}).
-- Generated by build_ld_round_dqa_scripts.py from the MNH PNC data dictionary.
-- ============================================================================
"""


def q(s):
    return "'" + s.replace("'", "''") + "'"


def build(cfg):
    t, rules = cfg["table"], cfg["rules"]
    src = "mahis_pnc_vitals.sql"
    rounds = f"rounds AS (\n    SELECT * FROM {t} WHERE {cfg['where']}\n)"
    read = lambda c: f", CASE WHEN {c} REGEXP {NUM_RX} THEN 1 ELSE 0 END AS numeric_reading" if cfg["reading"] else ""
    status = "field_status AS (\n" + "\n    UNION ALL\n".join(
        f"    SELECT encounter_id, person_id, {q(c)} AS field, CASE WHEN {c} IS NOT NULL THEN 1 ELSE 0 END AS present{read(c)} FROM rounds" for c, _, _ in rules) + "\n)"
    rulesq = "rules AS (\n" + "\n    UNION ALL\n".join(f"    SELECT {q(c)} AS field, {q(d)} AS dictionary_name, {q(l)} AS label" for c, d, l in rules) + "\n)"
    rd = """round_dq AS (
    SELECT encounter_id, person_id,
        COUNT(*) AS mandatory_fields,
        SUM(present) AS mandatory_present,
        COUNT(*) - SUM(present) AS mandatory_missing,
        GROUP_CONCAT(CASE WHEN present = 0 THEN field END ORDER BY field SEPARATOR '; ') AS missing_mandatory_fields
    FROM field_status
    GROUP BY encounter_id, person_id
)"""
    U, Us = cfg["unit"], cfg["units"]
    overall = f"""
SELECT 'Total {U}s' AS measure, COUNT(*) AS {Us}, 100.0 AS pct FROM round_dq
UNION ALL SELECT 'Women with at least one {U}', COUNT(DISTINCT person_id), NULL FROM round_dq
UNION ALL SELECT '{U.capitalize()}s with ALL mandatory fields present', SUM(mandatory_missing = 0), ROUND(100 * SUM(mandatory_missing = 0) / COUNT(*), 1) FROM round_dq
UNION ALL SELECT '{U.capitalize()}s with MISSING mandatory fields', SUM(mandatory_missing > 0), ROUND(100 * SUM(mandatory_missing > 0) / COUNT(*), 1) FROM round_dq
UNION ALL SELECT 'Average mandatory completeness (% of mandatory fields present per {U})', COUNT(*), ROUND(AVG(100 * mandatory_present / mandatory_fields), 1) FROM round_dq;
"""
    extra = (",\n    SUM(f.numeric_reading) AS " + Us + "_with_numeric_reading,\n    ROUND(100 * SUM(f.numeric_reading) / COUNT(*), 1) AS pct_with_numeric_reading") if cfg["reading"] else ""
    fields = f"""
SELECT
    r.field,
    r.dictionary_name,
    r.label,
    COUNT(*) AS {Us}_required,
    SUM(f.present) AS {Us}_present,
    COUNT(*) - SUM(f.present) AS {Us}_missing,
    ROUND(100 * SUM(f.present) / COUNT(*), 1) AS pct_present,
    ROUND(100 * (COUNT(*) - SUM(f.present)) / COUNT(*), 1) AS pct_missing{extra},
    CASE WHEN SUM(f.present) = COUNT(*) THEN 'COMPLETE' WHEN SUM(f.present) = 0 THEN 'ALL MISSING' ELSE 'PARTIAL' END AS status
FROM rules r
INNER JOIN field_status f ON f.field = r.field
GROUP BY r.field, r.dictionary_name, r.label
ORDER BY pct_present, r.field;
"""
    flags = f"""
SELECT
    {cfg['id_cols']},
    d.mandatory_fields, d.mandatory_present, d.mandatory_missing,
    ROUND(100 * d.mandatory_present / d.mandatory_fields, 1) AS pct_mandatory_present,
    CASE WHEN d.mandatory_missing = 0 THEN 'YES' ELSE 'NO' END AS all_mandatory_present,
    d.missing_mandatory_fields
FROM rounds m
INNER JOIN round_dq d ON d.encounter_id = m.encounter_id AND d.person_id = m.person_id
ORDER BY d.mandatory_missing DESC, m.person_id, m.visit_date;
"""
    hdr = lambda title: HEADER.format(title=f"{cfg['title']} - {title}", table=t, src=src)
    n1, n2, n3, n4 = cfg["nums"]
    for num, name, title, ctes, final in [
        (n1, f"{cfg['tag']}_overall", "OVERALL (each unit assessed on its own)", [rounds, status, rd], overall),
        (n2, f"{cfg['tag']}_by_field", "FIELD COMPLETENESS", [rounds, rulesq, status], fields),
        (n3, f"{cfg['tag']}_flags", "PER-ROW FLAGS", [rounds, status, rd], flags)]:
        open(os.path.join(HERE, f"{num:02d}_{name}.sql"), "w").write(hdr(title) + "WITH " + ",\n\n".join(ctes) + "\n" + final)
    with open(os.path.join(HERE, f"{n4:02d}_{cfg['tag']}_fields_not_assessable.sql"), "w") as f:
        f.write(f"-- {cfg['title']}: dictionary fields that cannot be assessed per {U}\nSELECT dictionary_name, label, reason FROM (\n")
        f.write("\n    UNION ALL\n".join(f"    SELECT {q(a)} AS dictionary_name, {q(b)} AS label, {q(c)} AS reason" for a, b, c in cfg["not_assessable"]))
        f.write("\n) x ORDER BY dictionary_name;\n")


for old in os.listdir(HERE):
    if re.match(r"0[6-9]_monitoring_", old):
        os.remove(os.path.join(HERE, old))
for cfg in CONFIGS:
    build(cfg)
print([c["tag"] for c in CONFIGS], "round-level scripts written")
